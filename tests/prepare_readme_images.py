#!/usr/bin/env python3
"""Convert the six reproducible Playwright mobile UI previews to compact WebP.

Images depict the bundled GlowQuest interface running in Chromium with a mocked
native BLE bridge. No user/device data is captured. Generated by GitHub Actions.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "reports" / "readme-previews"
DESTINATION = ROOT / "docs" / "screenshots"
SCREENS = ("colors", "mix", "effect-studio", "fireworks", "range-lab", "scout", "show-capture")
MAX_WIDTH = 640

def main():
    DESTINATION.mkdir(parents=True, exist_ok=True)
    for name in SCREENS:
        source = SOURCE / f"{name}.png"
        if not source.is_file():
            raise SystemExit(f"Missing required README screenshot: {source}")
        with Image.open(source) as image:
            image = image.convert("RGB")
            if image.width > MAX_WIDTH:
                h = round(image.height * MAX_WIDTH / image.width)
                image = image.resize((MAX_WIDTH, h), Image.Resampling.LANCZOS)
            destination = DESTINATION / f"{name}.webp"
            image.save(destination, format="WEBP", quality=82, method=6)
            print(f"README screenshot: {name}: {image.width}x{image.height}, "
                  f"{destination.stat().st_size:,} bytes")
    print("Optimized all six gallery screenshots successfully.")

if __name__ == "__main__":
    main()
